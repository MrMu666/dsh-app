// 页面实例池：用于在浏览页面时保留 iframe 实例，避免频繁重新加载。
//
// 规则：48 小时内再次进入同一地址时直接复用内存中的页面实例（不重新加载、
// 不清空页面状态/缓存）；超过 48 小时或强制刷新时才重新加载。

/** 页面实例保留时长（毫秒）：48 小时 */
export const POOL_TTL_MS = 48 * 60 * 60 * 1000;

/** 池中最多保留的页面实例数（超出时移除最久未用的，下次访问会重新加载） */
export const MAX_POOL_SIZE = 10;

/** 页面实例池条目 */
export interface PoolEntry {
  /** 最后使用时间戳（毫秒） */
  lastUsed: number;
  /** 代次：变化时强制重建 iframe（强制刷新/过期重建） */
  gen: number;
}
