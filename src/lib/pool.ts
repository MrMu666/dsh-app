// 页面实例池：用于在浏览页面时保留 iframe 实例，避免频繁重新加载。
//
// 规则：页面实例永久保留（不因时间过期而自动重载），再次进入同一地址时直接复用
// 内存中的页面实例（不重新加载、不清空页面状态/缓存）；只有点击强制刷新时才重新加载。
// 受池容量上限约束：超过 MAX_POOL_SIZE 时仍会移除最久未用的实例（下次访问会重新加载）。

/** 池中最多保留的页面实例数（超出时移除最久未用的，下次访问会重新加载） */
export const MAX_POOL_SIZE = 10;

/** 页面实例池条目 */
export interface PoolEntry {
  /** 最后使用时间戳（毫秒） */
  lastUsed: number;
  /** 代次：变化时强制重建 iframe（目前仅强制刷新会触发） */
  gen: number;
}
